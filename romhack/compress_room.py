from dataclasses import dataclass
from classes import Sprite, Room

@dataclass
class PenCommand:
    tile: int
    def __str__(self):
        return "PEN(" + format(self.tile, "02X") + ")"

@dataclass
class CopypastaCommand:
    num_tiles: int
    copy_start: int
    def __str__(self):
        return "COPYPASTA(" + format(self.num_tiles, "02X") + ", " + format(self.copy_start, "02X") + ")"

TILES_PER_ROOM = 15*16

def best(cursor, copy_start, target):
    fail = False
    i = 0
    while fail == False and i < 0x7F and cursor + i < TILES_PER_ROOM:
        if copy_start < cursor:
            if target[ cursor + i ] != target[ copy_start + ( i % ( cursor - copy_start ) ) ]:
                fail = True
        else:
            if target[ cursor + i ] != 0x00:
                fail = True
    
        if fail == False:
            i += 1

    return i

def best2(cursor, target):
    copy_start = cursor
    best_score = 0
    best_copy_start = 0

    while copy_start >= 0x00:
        candidate = best(cursor, copy_start, target)
        if candidate > best_score:
            best_score = candidate
            best_copy_start = copy_start
        copy_start -= 1

    return (best_score, best_copy_start)

